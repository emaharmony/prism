func TestDefaultConfig(t *testing.T) {
	cfg := DefaultConfig()

	if cfg.Prism.LogLevel != "info" {
		t.Errorf("expected default log level 'info', got %q", cfg.Prism.LogLevel)
	}
	if cfg.Sessions.IdleTimeoutMinutes != 30 {
		t.Errorf("expected default idle timeout 30, got %d", cfg.Sessions.IdleTimeoutMinutes)
	}
	if cfg.Sessions.DailyResetHour != 4 {
		t.Errorf("expected default daily reset hour 4, got %d", cfg.Sessions.DailyResetHour)
	}
	if cfg.Sessions.MaxContextMessages != 100 {
		t.Errorf("expected default max context 100, got %d", cfg.Sessions.MaxContextMessages)
	}
	if cfg.Sessions.CompactionStrategy != "truncate" {
		t.Errorf("expected default compaction 'truncate', got %q", cfg.Sessions.CompactionStrategy)
	}
	if cfg.Remembrance.Enabled != false {
		t.Error("expected remembrance disabled by default")
	}
}

