func TestValidAgentIDs(t *testing.T) {
	tests := []struct {
		id    string
		valid bool
	}{
		{"lumi", true},
		{"mango", true},
		{"prism1", true},
		{"support-bot", true},
		{"sales-agent", true},
		{"a", true},
		{"abc123", true},
		{"bad.id", false},
		{"bad_id", false},
		{"Bad", false},
		{"", false},
		{"a.b", false},
	}

	for _, tt := range tests {
		got := isValidAgentID(tt.id)
		if got != tt.valid {
			t.Errorf("isValidAgentID(%q) = %v, want %v", tt.id, got, tt.valid)
		}
	}
}